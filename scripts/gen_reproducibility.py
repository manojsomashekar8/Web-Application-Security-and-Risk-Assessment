"""Write docs/REPRODUCIBILITY.md from the live host: OS, Docker, CPU/RAM, image digests, lock + feed hashes."""
import datetime as dt
import hashlib
import json
import os
import pathlib
import platform
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]


def sh(cmd: str) -> str:
    return subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=ROOT).stdout.strip() or "n/a"


def digest(image: str) -> str:
    return sh(f"docker image inspect --format '{{{{index .RepoDigests 0}}}}' {image}")


def main() -> None:
    images = sh("docker compose config --format json").splitlines()
    cfg = json.loads(sh("docker compose config --format json") or "{}")
    rows = []
    for name, svc in cfg.get("services", {}).items():
        img = svc.get("image", "build: ./Dockerfile")
        rows.append(f"| {name} | `{img}` |")
    lock = hashlib.sha256((ROOT / "requirements.lock").read_bytes()).hexdigest()
    manifest = (ROOT / "data" / "feeds" / "manifest.json")
    mhash = hashlib.sha256(manifest.read_bytes()).hexdigest() if manifest.exists() else "n/a"
    mem_kb = next((l.split()[1] for l in open("/proc/meminfo") if l.startswith("MemTotal")), "0")
    text = f"""# Reproducibility

Generated by `scripts/gen_reproducibility.py` on {dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')}. Do not edit by hand.

## Host
- OS: {sh('lsb_release -ds')} (kernel {platform.release()})
- CPU: {os.cpu_count()} logical cores, {platform.machine()}
- RAM: {round(int(mem_kb) / 1024 / 1024, 1)} GiB
- Docker: {sh('docker version --format "{{{{.Server.Version}}}}"')}; Compose: {sh('docker compose version --short')}
- Python: {platform.python_version()}

## Images (tag @ digest, from docker-compose.yml)
| Service | Image reference |
|---|---|
""" + "\n".join(rows) + f"""

## Locked Python dependencies
- requirements.lock SHA-256: `{lock}`

## Feed snapshot
- data/feeds/manifest.json SHA-256: `{mhash}`
- Manifest contents: see data/feeds/manifest.json
"""
    (ROOT / "docs" / "REPRODUCIBILITY.md").write_text(text)
    print("wrote docs/REPRODUCIBILITY.md")


if __name__ == "__main__":
    main()
